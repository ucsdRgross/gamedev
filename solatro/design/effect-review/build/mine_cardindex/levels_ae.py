# -*- coding: utf-8 -*-
"""Rewrite `levels/lAE.py` from the `LEVEL2` and `FLAGS` of every family-AE module.

A family-AE module carries its level 2 beside its rows, keyed by eid, because the question id only
exists once `render.py` has numbered the family. Run it after every render that adds or renames an
AE row, then render again so the level 2 appears.

    py levels_ae.py
"""
import glob, importlib.util, io, os, re, sys

BUILD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BUILD)
import levels

level2, flags, names = {}, {}, []
for p in sorted(glob.glob(os.path.join(BUILD, "generated", "g*.py"))):
    spec = importlib.util.spec_from_file_location("g_" + os.path.basename(p)[:-3], p)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    if not hasattr(m, "LEVEL2"):
        continue
    assert set(m.LEVEL2) == {r[0] for r in m.ROWS}, ("LEVEL2 and ROWS disagree in", p)
    level2.update(m.LEVEL2)
    flags.update(getattr(m, "FLAGS", {}))
    names += [(r[0], r[1]) for r in m.ROWS]

def key(name):
    """A name as the v2 rule compares it: case, a leading "The" and a " vN" suffix ignored."""
    n = re.sub(r" v\d+$", "", name.strip().lower())
    return n[4:] if n.startswith("the ") else n


# The v2 rule (WRITE_PROMPT.md § Names): an AE effect under a name a live question or an earlier
# AE row already holds carries a suffix.
seen = {key(re.match(r"\*\*(.+?)\*\*", q["text"]).group(1)): qid
        for qid, q in levels.questions().items() if q["live"] and q["fam"] != "AE"}
bare = []
for eid, name in names:
    if key(name) in seen and not re.search(r" v\d+$", name):
        bare.append("%s %s repeats %s" % (eid, name, seen[key(name)]))
    seen.setdefault(key(name), eid)
if bare:
    raise SystemExit("!! an AE name repeats a taken name without v2:\n  " + "\n  ".join(bare))

q2e = levels.order()
rows = [(q, e) for q, e in q2e.items() if e in level2]
assert len(rows) == len(level2), "an AE eid did not render"
with io.open(os.path.join(BUILD, "levels", "lAE.py"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# -*- coding: utf-8 -*-\n# Family AE: (qid, eid, verdict, level2, why) - schema in ../levels.py.\n"
            "# GENERATED by mine_cardindex/levels_ae.py from each module's LEVEL2 and FLAGS.\n\nROWS = [\n")
    for q, e in rows:
        f.write("(%r, %r, %r, %r, %r),\n" % (q, e, "WEAK" if e in flags else "OK", level2[e], flags.get(e, "")))
    f.write("]\n")
print("wrote levels/lAE.py: %d rows, %d flagged" % (len(rows), len(flags)))
